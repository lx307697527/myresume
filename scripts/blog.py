def cmd_build(args) -> int:
    errors = []
    posts = load_posts(errors)
    if errors:
        print("\n".join("FAIL: " + e for e in errors))
        return 1
    files = render_all(posts)
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    for d in orphan_dirs(posts):
        (d / "index.html").unlink()
        if not any(d.iterdir()):
            d.rmdir()
        print(f"removed {d.relative_to(ROOT)}")
    print(f"ok: {len(posts)} 份源稿,{len(files)} 个产物")
    return 0


def cmd_check(args) -> int:
    errors = []
    posts = load_posts(errors)
    if not posts and not errors:
        errors.append("一篇文章都没有(检查不能在没有输入时报绿)")
    deny = load_denylist(args.denylist)
    if args.strict and not deny:
        errors.append("--strict 模式必须提供私有敏感词表(--denylist 文件 或 环境变量 BLOG_DENYLIST),否则不放行")
    errors += quality_errors(posts)
    errors += redline_errors(posts, deny)
    key_file = ROOT / f"{INDEXNOW_KEY}.txt"
    if not key_file.is_file() or key_file.read_text(encoding="utf-8").strip() != INDEXNOW_KEY:
        errors.append(f"缺 IndexNow 密钥文件 {key_file.name}(内容必须等于密钥)")
    if not errors:
        for path, content in render_all(posts).items():
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                errors.append(f"产物不是最新:{path.relative_to(ROOT)}(先跑 python3 scripts/blog.py build)")
        for d in orphan_dirs(posts):
            errors.append(f"残留的旧文章目录:{d.relative_to(ROOT)}(先跑 build)")
    if errors:
        print("\n".join("FAIL: " + e for e in errors))
        print(f"\n共 {len(errors)} 个问题,不放行。")
        return 1
    n_zh = sum(1 for p in posts if p.lang == "zh")
    print(f"PASS: {n_zh} 篇 × 中英两版;质量门槛、信息安全红线(私有词条 {len(deny)} 个)、产物同步全部通过。")
    return 0


