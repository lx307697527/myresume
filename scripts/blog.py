# ============================================================ 基础工具
def esc(s: str) -> str:
    return html.escape(s, quote=True)


def width(s: str) -> int:
    """显示宽度:中日韩全角字符算 2,其余算 1(估算搜索结果里标题会不会被截断)。"""
    return sum(2 if unicodedata.east_asian_width(c) in ("W", "F") else 1 for c in s)


def words(s: str) -> int:
    return len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'’\-]*", s))


def jsonld(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, indent=2).replace("</", "<\\/")


def iso_dt(d: str) -> str:
    y, m, dd = map(int, d.split("-"))
    return datetime(y, m, dd, 8, 0, tzinfo=TZ).isoformat()


def rfc822(d: str) -> str:
    y, m, dd = map(int, d.split("-"))
    return format_datetime(datetime(y, m, dd, 8, 0, tzinfo=TZ))


def source_hash(raw: str) -> str:
    return hashlib.sha256(("allyos:" + raw.strip().upper()).encode()).hexdigest()[:12]


# ============================================================ Markdown(够用的子集)
LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")
UL_RE = re.compile(r"^[-*]\s+")
OL_RE = re.compile(r"^\d+\.\s+")


def is_internal(url: str) -> bool:
    u = html.unescape(url)
    return urllib.parse.urlparse(u).hostname in (SITE_HOST, "www." + SITE_HOST)


def inline(text: str) -> str:
    out = []
    for part in re.split(r"(`[^`]+`)", text):
        if len(part) >= 2 and part[0] == "`" and part[-1] == "`":
            out.append("<code>" + esc(part[1:-1]) + "</code>")
            continue
        t = esc(part)

        def link(m):
            label, url = m.group(1), m.group(2)
            extra = "" if is_internal(url) or url.startswith("#") else ' target="_blank" rel="noopener"'
            return f'<a href="{url}"{extra}>{label}</a>'

        t = LINK_RE.sub(link, t)
        t = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", t)
        out.append(t)
    return "".join(out)


def strip_md(text: str) -> str:
    text = LINK_RE.sub(lambda m: m.group(1), text)
    text = text.replace("**", "").replace("`", "")
    return re.sub(r"\s+", " ", text).strip()


def join_lines(lines: list[str], lang: str) -> str:
    if lang == "en":
        return " ".join(lines)
    out = ""
    for ln in lines:
        if out and out[-1].isascii() and out[-1].isalnum() and ln[:1].isascii() and ln[:1].isalnum():
            out += " "
        out += ln
    return out


def is_block_start(s: str) -> bool:
    s = s.strip()
    return bool(s.startswith("```") or re.match(r"^#{1,6}\s", s) or s.startswith("|")
                or s.startswith(">") or UL_RE.match(s) or OL_RE.match(s))


def render_table(rows: list[str]) -> str:
    def cells(r):
        r = r.strip()
        if r.startswith("|"):
            r = r[1:]
        if r.endswith("|"):
            r = r[:-1]
        return [c.strip() for c in r.split("|")]

    head = cells(rows[0])
    body = [cells(r) for r in rows[2:]]
    h = "".join(f"<th>{inline(c)}</th>" for c in head)
    b = "".join("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>" for r in body)
    return f'<div class="table-wrap"><table><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table></div>'


@dataclass
class Rendered:
    html: str
    h2s: list
    faq: list
    code_blocks: list
    tables: int
    errors: list


def render_markdown(md: str, lang: str) -> Rendered:
    lines = md.split("\n")
    out, h2s, faq, codes, errors = [], [], [], [], []
    tables = 0
    in_faq = False
    cur_q, cur_a = None, []

    def flush_q():
        nonlocal cur_q, cur_a
        if cur_q is not None:
            faq.append((cur_q, " ".join(cur_a).strip()))
        cur_q, cur_a = None, []

    def add_answer(text):
        if in_faq and cur_q is not None:
            cur_a.append(strip_md(text))

    i, n = 0, len(lines)
    while i < n:
        s = lines[i].strip()
        if not s:
            i += 1
            continue
        if s.startswith("```"):
            tag = s[3:].strip()
            j, buf = i + 1, []
            while j < n and not lines[j].strip().startswith("```"):
                buf.append(lines[j])
                j += 1
            if j >= n:
                errors.append("代码块没有闭合 ```")
            codes.append(buf)
            cls = f' class="language-{esc(tag)}"' if tag else ""
            out.append(f"<pre><code{cls}>{esc(chr(10).join(buf))}</code></pre>")
            i = j + 1
            continue
        m = re.match(r"^(#{1,6})\s+(.*)$", s)
        if m:
            level, text = len(m.group(1)), m.group(2).strip()
            if level == 1:
                errors.append("正文不能用一级标题 #(页面标题来自 front matter 的 title)")
            elif level == 2:
                flush_q()
                in_faq = text in FAQ_HEADINGS
                h2s.append(text)
                out.append(f'<h2 id="s{len(h2s)}">{inline(text)}</h2>')
            elif level == 3:
                if in_faq:
                    flush_q()
                    cur_q = strip_md(text)
                out.append(f"<h3>{inline(text)}</h3>")
            else:
                out.append(f"<h4>{inline(text)}</h4>")
            i += 1
            continue
        if s.startswith("|") and i + 1 < n and re.match(r"^\|?\s*:?-{3,}", lines[i + 1].strip()):
            j, rows = i, []
            while j < n and lines[j].strip().startswith("|"):
                rows.append(lines[j])
                j += 1
            out.append(render_table(rows))
            tables += 1
            i = j
            continue
        if s.startswith(">"):
            buf = []
            while i < n and lines[i].strip().startswith(">"):
                buf.append(lines[i].strip()[1:].strip())
                i += 1
            text = join_lines(buf, lang)
            out.append(f"<blockquote><p>{inline(text)}</p></blockquote>")
            add_answer(text)
            continue
        if UL_RE.match(s) or OL_RE.match(s):
            pat = OL_RE if OL_RE.match(s) else UL_RE
            items = []
            while i < n:
                raw = lines[i]
                if pat.match(raw.strip()) and not raw.startswith((" ", "\t")):
                    items.append(pat.sub("", raw.strip()))
                elif raw.strip() and raw.startswith((" ", "\t")) and items:
                    items[-1] = join_lines([items[-1], raw.strip()], lang)
                else:
                    break
                i += 1
            tag = "ol" if pat is OL_RE else "ul"
            out.append(f"<{tag}>" + "".join(f"<li>{inline(x)}</li>" for x in items) + f"</{tag}>")
            add_answer(" ".join(items))
            continue
        buf = []
        while i < n and lines[i].strip() and not is_block_start(lines[i]):
            buf.append(lines[i].strip())
            i += 1
        text = join_lines(buf, lang)
        out.append(f"<p>{inline(text)}</p>")
        add_answer(text)
    flush_q()
    return Rendered("\n".join(out), h2s, faq, codes, tables, errors)


def body_size(md: str, lang: str) -> int:
    text = re.sub(r"```.*?```", "", md, flags=re.S)
    text = LINK_RE.sub(lambda m: m.group(1), text)
    if lang == "en":
        return words(text)
    text = re.sub(r"[#|*>`\-]", "", text)
    return len(re.sub(r"\s", "", text))


