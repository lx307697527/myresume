@dataclass
class Post:
    slug: str
    lang: str
    path: Path
    meta: dict
    body: str
    r: Rendered | None = None
    size: int = 0
    tags: list = field(default_factory=list)
    sources: list = field(default_factory=list)

    @property
    def rel_dir(self) -> str:
        return UI[self.lang]["blog_dir"] + self.slug + "/"

    @property
    def url(self) -> str:
        return SITE + "/" + self.rel_dir

    @property
    def out_path(self) -> Path:
        return ROOT / self.rel_dir / "index.html"

    @property
    def pillar_name(self) -> str:
        return PILLARS[self.meta["pillar"]][self.lang]

    @property
    def minutes(self) -> int:
        return max(1, round(self.size / (450 if self.lang == "zh" else 230)))


NAME_RE = re.compile(r"^([a-z0-9]+(?:-[a-z0-9]+)*)\.(zh|en)\.md$")


def parse_post(path: Path, errors: list) -> Post | None:
    m = NAME_RE.match(path.name)
    if not m:
        errors.append(f"{path.name}: 文件名必须是 <英文短链>.zh.md / <英文短链>.en.md(小写字母、数字、连字符)")
        return None
    slug, lang = m.group(1), m.group(2)
    if len(slug) > 60:
        errors.append(f"{path.name}: 短链超过 60 个字符")
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    if not text.startswith("---\n"):
        errors.append(f"{path.name}: 缺 front matter(第一行必须是 ---)")
        return None
    end = text.find("\n---\n", 4)
    if end < 0:
        errors.append(f"{path.name}: front matter 没有用 --- 收尾")
        return None
    meta = {}
    for ln in text[4:end].split("\n"):
        if not ln.strip() or ln.lstrip().startswith("#"):
            continue
        fm = re.match(r"^([a-z_]+):\s*(.*)$", ln)
        if not fm:
            errors.append(f"{path.name}: 看不懂的 front matter 行:{ln[:40]}")
            continue
        k, v = fm.group(1), fm.group(2).strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
            v = v[1:-1]
        if k not in KNOWN_KEYS:
            errors.append(f"{path.name}: 未知字段 {k}")
        meta[k] = v
    post = Post(slug, lang, path, meta, text[end + 5:])
    post.tags = [t.strip() for t in re.split(r"[,,]", meta.get("tags", "")) if t.strip()]
    post.sources = [t.strip() for t in meta.get("source", "").split(",") if t.strip()]
    return post


def load_posts(errors: list) -> list[Post]:
    if not POSTS_DIR.is_dir():
        errors.append(f"找不到源稿目录 {POSTS_DIR.relative_to(ROOT)}")
        return []
    posts = []
    for p in sorted(POSTS_DIR.glob("*.md")):
        post = parse_post(p, errors)
        if post is None:
            continue
        missing = [k for k in REQUIRED_KEYS if not post.meta.get(k)]
        if missing:
            errors.append(f"{p.name}: 缺字段 {', '.join(missing)}")
            continue
        if post.meta["pillar"] not in PILLARS:
            errors.append(f"{p.name}: pillar 必须是 {', '.join(PILLARS)} 之一")
            continue
        bad_date = False
        for k in ("date", "updated"):
            try:
                Date.fromisoformat(post.meta[k])
            except ValueError:
                errors.append(f"{p.name}: {k} 必须是 YYYY-MM-DD")
                bad_date = True
        if bad_date:
            continue
        post.r = render_markdown(post.body, post.lang)
        post.size = body_size(post.body, post.lang)
        posts.append(post)
    return posts


def newest_first(posts):
    return sorted(posts, key=lambda p: (p.meta["date"], p.meta["updated"], p.slug), reverse=True)


