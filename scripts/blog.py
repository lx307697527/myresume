def render_all(posts: list[Post]) -> dict[Path, str]:
    by = {(p.slug, p.lang): p for p in posts}
    zh = newest_first([p for p in posts if p.lang == "zh" and (p.slug, "en") in by])
    en = newest_first([p for p in posts if p.lang == "en" and (p.slug, "zh") in by])
    files = {}
    for p in zh + en:
        twin = by[(p.slug, "en" if p.lang == "zh" else "zh")]
        files[p.out_path] = render_post(p, twin, zh if p.lang == "zh" else en)
    files[ROOT / "blog/index.html"] = render_index("zh", zh)
    files[ROOT / "en/blog/index.html"] = render_index("en", en)
    files[ROOT / "blog/feed.xml"] = render_feed("zh", zh)
    files[ROOT / "en/blog/feed.xml"] = render_feed("en", en)
    files[ROOT / "sitemap.xml"] = render_sitemap(zh, {p.slug: p for p in en})
    files[ROOT / "llms.txt"] = render_llms(zh, en)
    files[ROOT / "index.html"] = render_home(zh)
    return files


def orphan_dirs(posts: list[Post]) -> list[Path]:
    keep = {p.out_path.parent for p in posts}
    found = []
    for base in (ROOT / "blog", ROOT / "en/blog"):
        if not base.is_dir():
            continue
        for d in base.iterdir():
            f = d / "index.html"
            if d.is_dir() and d not in keep and f.is_file() and GEN_MARK in f.read_text(encoding="utf-8"):
                found.append(d)
    return found


