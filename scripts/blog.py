def cmd_indexnow(args) -> int:
    after = args.after
    before = args.before if args.before and set(args.before) != {"0"} else f"{after}~1"
    diff = subprocess.run(["git", "diff", "--name-only", before, after], cwd=ROOT, capture_output=True,
                          text=True, env={**os.environ, "LC_ALL": "C.UTF-8"})
    if diff.returncode != 0:
        print("FAIL: git diff 失败:" + diff.stderr.strip())
        return 1
    urls = [SITE + "/" + f[: -len("index.html")] for f in diff.stdout.split()
            if re.fullmatch(r"(?:(?:en/)?blog|notes)/(?:[a-z0-9\-]+/)?index\.html", f)]
    if not urls:
        print("ok: 这次推送没有文章页面变化,不需要通知")
        return 0
    deadline = time.time() + args.wait
    while True:  # 等线上部署完成(新文章不再 404)再通知,否则 Bing 来抓会扑空
        try:
            with urllib.request.urlopen(urllib.request.Request(urls[0], method="HEAD"), timeout=20) as r:
                if r.status == 200:
                    break
        except Exception:
            pass
        if time.time() > deadline:
            print(f"FAIL: 等了 {args.wait} 秒,{urls[0]} 仍未上线")
            return 1
        time.sleep(15)
    payload = {"host": SITE_HOST, "key": INDEXNOW_KEY, "keyLocation": f"{SITE}/{INDEXNOW_KEY}.txt", "urlList": urls}
    req = urllib.request.Request("https://api.indexnow.org/indexnow", data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json; charset=utf-8"}, method="POST")
    with urllib.request.urlopen(req, timeout=30) as r:
        if r.status not in (200, 202):
            print(f"FAIL: IndexNow 返回 {r.status}")
            return 1
    print(f"ok: 已通知 IndexNow {len(urls)} 个地址:\n" + "\n".join(urls))
    return 0


