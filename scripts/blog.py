def render_sitemap(zh_posts: list[Post], en_by_slug: dict) -> str:
    current = (ROOT / "sitemap.xml").read_text(encoding="utf-8")
    static = []
    for block in re.findall(r"<url>(.*?)</url>", current, flags=re.S):
        loc = re.search(r"<loc>(.*?)</loc>", block).group(1).strip()
        if loc.startswith(SITE + "/blog/") or loc.startswith(SITE + "/en/blog/"):
            continue
        fields = {k: (re.search(rf"<{k}>(.*?)</{k}>", block) or [None, None])[1] for k in
                  ("lastmod", "changefreq", "priority")}
        static.append((loc, fields))

    def entry(loc, lastmod, freq, prio, alts=None):
        alt = ""
        if alts:
            alt = "".join(f'\n    <xhtml:link rel="alternate" hreflang="{h}" href="{u}" />' for h, u in alts)
        return (f"  <url>\n    <loc>{loc}</loc>{alt}\n    <lastmod>{lastmod}</lastmod>\n"
                f"    <changefreq>{freq}</changefreq>\n    <priority>{prio}</priority>\n  </url>")

    out = [entry(loc, f["lastmod"], f["changefreq"], f["priority"]) for loc, f in static]
    if zh_posts:
        last = max(p.meta["updated"] for p in zh_posts)
        idx_alts = [("zh-CN", SITE + "/blog/"), ("en", SITE + "/en/blog/"), ("x-default", SITE + "/blog/")]
        out.append(entry(SITE + "/blog/", last, "daily", "0.7", idx_alts))
        out.append(entry(SITE + "/en/blog/", last, "daily", "0.7", idx_alts))
        for p in zh_posts:
            e = en_by_slug[p.slug]
            alts = [("zh-CN", p.url), ("en", e.url), ("x-default", p.url)]
            out.append(entry(p.url, p.meta["updated"], "monthly", "0.6", alts))
            out.append(entry(e.url, e.meta["updated"], "monthly", "0.6", alts))
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n'
            '        xmlns:xhtml="http://www.w3.org/1999/xhtml">\n' + "\n".join(out) + "\n</urlset>\n")


def replace_block(text: str, start: str, end: str, block: str, name: str, append_if_missing: bool):
    if start in text and end in text:
        a = text.index(start)
        b = text.index(end) + len(end)
        return text[:a] + block + text[b:]
    if append_if_missing:
        return text.rstrip("\n") + "\n\n" + block + "\n"
    raise SystemExit(f"FAIL: {name} 里找不到标记 {start!r} / {end!r}(不猜位置,请先手动放好标记)")


