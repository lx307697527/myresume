    ("AllyOS 真实库表名(schema.table)", r"\b(?:crm|pricing|billing|sales|production|procurement|platform|catalog|"
                                    r"sample|hr|integrations|security|marketing|comms|scheduling|migration|feedback)\.[a-z_]{3,}\b"),
